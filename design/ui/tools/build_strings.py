def main():
    keys = [k for k,_,_ in S]
    assert len(keys) == len(set(keys)), "duplicate keys"
    zh = {k: z for k, z, _ in S}
    en = {k: e for k, _, e in S}
    for name, d in (("strings_zh.json", zh), ("strings_en.json", en)):
        with open(os.path.join(ROOT, name), "w", encoding="utf-8", newline="\n") as f:
            json.dump(d, f, ensure_ascii=False, indent=2); f.write("\n")
    with open(os.path.join(ROOT, "prototype", "strings.js"), "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/build_strings.py - do not edit\n")
        f.write("window.STRINGS = " + json.dumps({"zh": zh, "en": en}, ensure_ascii=False, indent=1) + ";\n")
    print(len(keys), "keys")
main()
